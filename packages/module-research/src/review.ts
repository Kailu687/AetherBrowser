/** Heuristic research-question refinement: a checklist, not a rewrite. */
export function refineQuestion(text: string): Array<{ check: string; ok: boolean; tip: string }> {
  const t = text.trim();
  const words = tokens(t);
  const lower = t.toLowerCase();
  return [
    { check: "Phrased as a question", ok: /\?\s*$/.test(t) || /^(how|what|which|why|does|do|is|are|can|to what extent|under what)\b/i.test(t), tip: "Write it as a question so it is clear what would count as an answer." },
    { check: "Specific enough", ok: words.length >= 7, tip: "Very short questions are usually too broad to review. Name the system, method or population." },
    { check: "Names a population, system or context", ok: /\b(in|for|among|on|within|of)\s+\w+/i.test(t), tip: "Say where it applies, e.g. “in low-power wearable ECG front ends”." },
    { check: "Names an intervention, method or factor", ok: /\b(using|with|via|by|effect of|impact of|influence of|role of|method|technique|approach|design)\b/i.test(lower), tip: "Say which method, design choice or factor you are studying." },
    { check: "Has a comparison", ok: /\b(compared|versus|vs\.?|than|relative to|against|difference)\b/i.test(lower), tip: "Optional: add what it is compared with, which makes evidence easier to judge." },
    { check: "Has a measurable outcome", ok: /\b(accuracy|error|noise|power|efficiency|cost|latency|yield|performance|reliability|rate|time|strength|life|throughput|outcome|effect)\b/i.test(lower), tip: "Name the outcome you will compare (e.g. noise, power, accuracy)." },
    { check: "Bounded in time (optional)", ok: /\b(since|between|after|before|19\d\d|20\d\d|recent|last \d+ years)\b/i.test(lower), tip: "Optional: limit the publication period so the review is feasible." },
  ];
}

export function refinePrompt(text: string, scope?: string): { system: string; prompt: string } {
  return {
    system: "You help engineers sharpen literature-review research questions. Suggest up to three clearer, answerable versions of the user's question, each on its own line, starting with '- '. Keep the user's topic; do not add claims, findings or citations.",
    prompt: `Question: ${text}${scope ? `\nScope: ${scope}` : ""}`,
  };
}

/** Benchmark view: which datasets were used with which metrics, from accepted extractions (labels). */
export function benchmarkTable(items: ExtractionItem[]): Array<{ dataset: string; metrics: string[]; sources: string[] }> {
  const acc = items.filter((i) => i.status === "accepted");
  const bySource = new Map<string, { datasets: string[]; metrics: string[] }>();
  for (const i of acc) {
    const e = bySource.get(i.sourceId) ?? { datasets: [], metrics: [] };
    if (i.field === "datasets") e.datasets.push(...(i.labels.length ? i.labels : [i.text]));
    if (i.field === "metrics") e.metrics.push(...(i.labels.length ? i.labels : [i.text]));
    bySource.set(i.sourceId, e);
  }
  const rows = new Map<string, { dataset: string; metrics: Set<string>; sources: Set<string> }>();
  for (const [src, e] of bySource) {
    for (const d of e.datasets) {
      const k = d.toLowerCase().trim();
      const r = rows.get(k) ?? { dataset: d, metrics: new Set<string>(), sources: new Set<string>() };
      e.metrics.forEach((m) => r.metrics.add(m));
      r.sources.add(src);
      rows.set(k, r);
    }
  }
  return [...rows.values()].map((r) => ({ dataset: r.dataset, metrics: [...r.metrics], sources: [...r.sources] })).sort((a, b) => b.sources.length - a.sources.length);
}

/** Full literature-review report in Markdown (for the Writer, or download). */
export function reviewReport(p: LabProject, questions: ResearchQuestion[], items: ExtractionItem[], outline: ReviewOutline, keptGaps: GapHypothesis[], at = new Date()): string {
  const c = screeningCounts(p);
  const L: string[] = [`# ${p.title}: literature review report`, "", `Generated by AETHER Research & Writing on ${at.toISOString().slice(0, 10)}. Every statement below links to the source it came from; check each against the paper before you rely on it.`, ""];
  L.push("## Scope and method", "");
  if (p.scope?.statement || p.description) L.push(p.scope?.statement || p.description || "", "");
  if (p.scope?.inclusion.length) L.push("**Inclusion criteria**", "", ...p.scope.inclusion.map((x) => `- ${x}`), "");
  if (p.scope?.exclusion.length) L.push("**Exclusion criteria**", "", ...p.scope.exclusion.map((x) => `- ${x}`), "");
  if (p.scope?.fromYear || p.scope?.toYear) L.push(`Publication years: ${p.scope.fromYear ?? "any"} to ${p.scope.toYear ?? "present"}.`, "");
  L.push("**Screening (PRISMA-style counts)**", "", `- Identified: ${c.identified}`, `- Included: ${c.included}`, `- Excluded: ${c.excluded}`, `- Undecided: ${c.maybe}`, `- Not yet screened: ${c.unscreened}`, "");
  const reasons = new Map<string, number>();
  for (const d of Object.values(p.screening)) if (d.status === "exclude") for (const r of d.criteria?.length ? d.criteria : [d.reason || "No reason recorded"]) reasons.set(r, (reasons.get(r) ?? 0) + 1);
  if (reasons.size) L.push("Exclusion reasons:", "", ...[...reasons].map(([r, n]) => `- ${r}: ${n}`), "");
  if (questions.length) {
    L.push("## Research questions", "");
    for (const q of questions.filter((x) => !x.parentId).sort((a, b) => a.order - b.order)) {
      L.push(`- ${q.text} (${q.status})`);
      for (const s of questions.filter((x) => x.parentId === q.id)) L.push(`  - ${s.text} (${s.status})`);
    }
    L.push("");
  }
  L.push("## Comparison matrix", "", matrixToMarkdown(buildMatrix(p, p.sources, items)), "");
  const bench = benchmarkTable(items.filter((i) => p.screening[i.sourceId]?.status !== "exclude"));
  if (bench.length) {
    L.push("## Datasets and benchmarks", "", "| Dataset | Metrics reported | Sources |", "|---|---|---|");
    for (const b of bench) L.push(`| ${b.dataset.replace(/\|/g, "\\|")} | ${b.metrics.join(", ").replace(/\|/g, "\\|") || "—"} | ${b.sources.map((s) => `[@${s}]`).join(" ")} |`);
    L.push("");
  }
  if (keptGaps.length) {
    L.push("## Possible research gaps (hypotheses)", "", "These are based only on the sources in this review; work outside it may already address them.", "");
    for (const g of keptGaps) L.push(`- ${g.statement} ${[...new Set(g.basis.map((b) => b.sourceId).filter(Boolean))].map((s) => `[@${s}]`).join(" ")}`);
    L.push("");
  }
  L.push(outlineToMarkdown(outline).replace(/^# .*\n/, "## Review outline\n"), "");
  L.push("## Included sources", "");
  for (const id of p.sourceIds.filter((s) => p.screening[s]?.status !== "exclude")) {
    const r: Reference | undefined = p.sources[id];
    L.push(`- **${id}**: ${sourceLabel(r, id)}, ${r?.title ?? "(no title)"}${r?.["container-title"] ? `, ${r["container-title"]}` : ""}${dateParts(r?.issued).year ? `` : ""}${r?.DOI ? `, doi:${r.DOI}` : ""}`);
  }
  return L.join("\n") + "\n";
}

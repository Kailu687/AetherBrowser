import type { LabProject, ResearchQuestion } from "./model.js";
import { buildMatrix, matrixToMarkdown, outlineToMarkdown, screeningCounts, sourceLabel, type GapHypothesis, type ReviewOutline } from "./analysis.js";
import type { ExtractionItem } from "./model.js";
